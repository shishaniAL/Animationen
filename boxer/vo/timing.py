# words.json (faster-whisper word stamps of vo/voice.mp3) -> src/canvas-core/boxerTiming.ts
import json
OFF = 0.6  # the voice starts this many seconds into the film
w = json.load(open('vo/words.json'))
fix = {'6am.': '6 AM.', 'Remember,': 'Remember…', 'victory,': 'victory.'}
segs, cur = [], []
for t, a, b in w:
    t = fix.get(t, t)
    cur.append([t, round(a + OFF, 3), round(b + OFF, 3)])
    if t.endswith('.') or t.endswith('…'):
        segs.append(cur); cur = []
if cur: segs.append(cur)
out = [{'text': ' '.join(x[0] for x in s), 'start': s[0][1], 'end': s[-1][2], 'words': s} for s in segs]
assert len(out) == 16, len(out)
end = 60.5  # the score is 18 bars at 75 bpm (57.6 s) plus its ring-out
open('src/canvas-core/boxerTiming.ts', 'w').write(
  '// generated by vo/timing.py from the voiceover\'s word stamps. Seconds of film time.\n'
  f'export const VO_OFFSET = {OFF};\nexport const FILM_END = {end};\n'
  'export type Word = [string, number, number];\nexport type Seg = { text: string; start: number; end: number; words: Word[] };\n'
  f'export const SEGS: Seg[] = {json.dumps(out)};\n')
for i, s in enumerate(out): print(i, s['start'], s['end'], s['text'])
print('end', end)
