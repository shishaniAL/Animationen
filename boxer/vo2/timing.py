# Writes src/canvas-core/dreamerTiming.ts. With vo2/words.json (word stamps of vo2/voice.mp3) it uses the real voice;
# without it, an estimate at the narrator's pace, so the picture can be built before the voice exists.
import json, os, sys
OFF = 0.6
lines = [l.strip() for l in open('vo2/script.txt') if l.strip()]
segs = []
if os.path.exists('vo2/words.json'):
    w = json.load(open('vo2/words.json'))[:186]; k = 0  # the take ends with a stray word after 'talking.', cut
    for l in lines:
        n = len(l.replace('…', '… ').split()); toks = l.replace('…', '… ').split()
        ws = w[k:k + n]; k += n
        segs.append({'text': l, 'start': round(ws[0][1] + OFF, 3), 'end': round(ws[-1][2] + OFF, 3), 'words': [[t, round(a[1] + OFF, 3), round(a[2] + OFF, 3)] for t, a in zip(toks, ws)]})
    assert k == len(w), (k, len(w))
else:
    t = OFF
    for l in lines:
        toks = l.replace('…', '… ').split(); ws = []
        for x in toks:
            d = 0.1 + 0.042 * len(x); ws.append([x, round(t, 3), round(t + d, 3)]); t += d + (0.3 if x[-1] in ',.…' else 0.02)
        segs.append({'text': l, 'start': ws[0][1], 'end': ws[-1][2], 'words': ws}); t += 0.25
QUOTE = round(segs[-1]['end'] + 1.4, 2)  # the end card's first line
end = round(QUOTE + 9.0, 2)
open('src/canvas-core/dreamerTiming.ts', 'w').write(
  "// generated by vo2/timing.py. Seconds of film time.\n" f"export const FILM_END = {end};\nexport const QUOTE = {QUOTE};\n"
  "export type Word = [string, number, number];\nexport type Seg = { text: string; start: number; end: number; words: Word[] };\n"
  f"export const SEGS: Seg[] = {json.dumps(segs)};\n")
for i, s in enumerate(segs): print(i, s['start'], s['end'], s['text'][:50])
print('end', end)
